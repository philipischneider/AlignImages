"""Refine automatic DICOM baselines by regions with bone/body and physical Z regularization."""
import argparse
from datetime import datetime, timezone
import json
from pathlib import Path

import cv2
import numpy as np
import torch

from dicom_ct import read_ct, ct_body, window_hu
from global_registration import extract_body
from local_registration import LocalSettings, fit_sequence, dense_field, fitted_field, jacobian, remap_native
from adaptive_regions import validate_regions
from deformation import FIELD_CONVENTION
from prepare import digest, read_image, write_png


def masked_dice(a, b, support=None):
    valid = np.ones(a.shape, bool) if support is None else support != 0
    aa, bb = (a != 0) & valid, (b != 0) & valid
    denominator = np.count_nonzero(aa) + np.count_nonzero(bb)
    return 2 * np.count_nonzero(aa & bb) / denominator if denominator else 1.


def save_intermediate_stages(run, fit, index, shape, transform, source_body, source_bone,
                             fixed_body, fixed_bone, support, record, check_cancel=lambda: None):
    """Persist actual end-of-level fields, before final acceptance/shrink gates."""
    stages = []
    for stage in fit["stages"]:
        check_cancel()
        field = fitted_field(fit, index, (fit["roi"][3], fit["roi"][2]), stage)
        j = jacobian(field)
        body = remap_native(source_body, transform, shape, field, fit["roi"], True)
        bone = remap_native(source_bone, transform, shape, field, fit["roi"], True)
        field_path = run / f"stage_{stage['level'] + 1:02d}_field.npz"
        np.savez_compressed(field_path, displacement_xy=field, roi=np.array(fit["roi"]),
                            output_shape=np.array(shape), convention=np.array(FIELD_CONVENTION))
        stages.append({"level": stage["level"], "count": stage["count"],
            "status": "intermediate_unvalidated", "field_path": str(field_path), "adaptive": stage.get("adaptive", False),
            "adaptive_regions": [r for r in fit.get("regions", []) if r["sequence_index"] == index] if stage.get("adaptive") else [],
            "sha256": digest(field_path), "roi": fit["roi"], "units": "photo_pixels",
            "settings": {**fit["settings"], "nodes": fit["settings"]["nodes"][:stage["level"] + 1]},
            "metrics": {"body_before": record["body_before"], "body_after": masked_dice(fixed_body, body),
                "bone_before": record["bone_before"], "bone_after": masked_dice(fixed_bone, bone, support),
                "max_displacement_px": float(np.linalg.norm(field, axis=2).max()),
                "minimum_jacobian": float(j.min()), "maximum_jacobian": float(j.max())}})
    return stages


def select_safe_field(field, transform, roi, source_body, source_bone, fixed_body, fixed_bone,
                      support, cfg, body_before, bone_before, base=None):
    base = np.zeros_like(field) if base is None else base
    for scale in [1., .5, .25, .125, 0.]:
        trial = base + field * scale
        j = jacobian(trial)
        bd = masked_dice(fixed_body, remap_native(source_body, transform, fixed_body.shape, trial, roi, True))
        od = masked_dice(fixed_bone, remap_native(source_bone, transform, fixed_body.shape, trial, roi, True), support)
        displacement = float(np.linalg.norm(trial, axis=2).max())
        safe = j.min() >= cfg.minimum_jacobian and j.max() <= 3. and displacement <= cfg.max_displacement_px + .001
        useful = bd >= body_before - .015 and od >= bone_before + .001
        if scale == 0 or (safe and useful):
            return trial, bd, od, displacement, float(j.min()), float(j.max()), scale


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--baseline", required=True, help="dicom_pilot.json generated by the automatic global motor")
    parser.add_argument("--annotations", required=True, help="photo_stack.json from fixed-crop mask restoration")
    parser.add_argument("--output", required=True, help="New experiment directory")
    parser.add_argument("--iterations", type=int, default=120, help="Iterations per lattice level")
    parser.add_argument("--working-size", type=int, default=256)
    parser.add_argument("--max-displacement-px", type=float, default=32.)
    parser.add_argument("--bone-threshold-hu", type=float, default=150.)
    parser.add_argument("--device", choices=["cpu", "cuda"], default="cpu")
    parser.add_argument("--nodes", type=int, nargs="+", default=[7, 13], help="Increasing lattice sizes, e.g. 7 13 25")
    parser.add_argument("--cancel-file", help="Stop cooperatively when this file exists")
    parser.add_argument("--regions", help="JSON with manual photo-space refine/protect regions")
    args = parser.parse_args()
    if (not args.nodes or min(args.nodes) < 3 or max(args.nodes) > 65 or
            any(a >= b for a, b in zip(args.nodes, args.nodes[1:])) or
            not 64 <= args.working_size <= 2048 or args.iterations < 1):
        parser.error("Use increasing lattice sizes 3..65, working size 64..2048 and positive iterations")
    def check_cancel():
        if args.cancel_file and Path(args.cancel_file).exists():
            raise KeyboardInterrupt
    baseline_path = Path(args.baseline).resolve()
    annotations_path = Path(args.annotations).resolve()
    baseline = json.loads(baseline_path.read_text(encoding="utf-8"))
    annotations = json.loads(annotations_path.read_text(encoding="utf-8"))
    requested_regions = validate_regions(json.loads(Path(args.regions).read_text(encoding="utf-8"))["regions"]) if args.regions else []
    if baseline.get("used_session_transform") is not False:
        parser.error("Expected an automatically computed baseline without session transforms")
    annotation_by_index = {item["index"]: item for item in annotations["slices"]}
    pairs = sorted(baseline["pairs"], key=lambda item: item["fixed_index"])
    if len({p["fixed_index"] for p in pairs}) != len(pairs):
        parser.error("Duplicate fixed indices")
    output = Path(args.output).resolve()
    protected = [baseline_path.parent, annotations_path.parent]
    for pair in pairs:
        data = json.loads(Path(pair["result"]).read_text(encoding="utf-8"))
        protected.extend(Path(item["path"]).resolve().parent for item in data["inputs"].values())
    if any(output == path or path in output.parents for path in protected):
        parser.error("Output must be separate from input experiments")
    cfg = LocalSettings(iterations=args.iterations, working_size=args.working_size, nodes=tuple(args.nodes),
                        max_displacement_px=args.max_displacement_px, device=args.device)
    output.mkdir(parents=True, exist_ok=False)
    audit = {"status": "preparing", "version": "regional_mesh_v1", "parameters": vars(args),
             "started_at": datetime.now(timezone.utc).isoformat(),
             "baseline_sha256": digest(baseline_path), "annotations_sha256": digest(annotations_path),
             "torch_version": torch.__version__, "pairs": [], "trace": []}
    audit["skipped_pairs"] = []
    fixed_bodies, moving_bodies, fixed_bones, moving_bones, supports, records, geometries, transforms = ([] for _ in range(8))
    try:
        for pair in pairs:
            check_cancel()
            index = pair["fixed_index"]
            source_result = Path(pair["result"])
            original = json.loads(source_result.read_text(encoding="utf-8"))
            item = annotation_by_index[index]
            fixed_path = Path(original["inputs"]["fixed"]["path"])
            if fixed_path.resolve() != Path(item["photo_path"]).resolve():
                raise ValueError(f"Annotation photograph mismatch at {index}")
            fixed = read_image(fixed_path)
            ct = read_ct(original["inputs"]["moving"]["path"])
            body = ct_body(ct)
            # Explicit experimental HU reference; no claim of an independently validated segmentation.
            bone = ((ct.hu >= args.bone_threshold_hu) & ct.valid & (body != 0)).astype(np.uint8)
            target_bone = (read_image(item["mask_path"], cv2.IMREAD_UNCHANGED) != 0).astype(np.uint8)
            if not np.any(target_bone) or not np.any(bone):
                audit["skipped_pairs"].append({"fixed_index": index, "reason": "empty_target_or_source_bone_mask"})
                print(f"Skipped {index}: empty bone reference; baseline preserved", flush=True)
                continue
            support_path = annotations_path.parent / "annotation_support" / Path(item["mask_path"]).name
            support = (read_image(support_path, cv2.IMREAD_UNCHANGED) != 0).astype(np.uint8)
            fixed_body = extract_body(fixed, "photo")
            if target_bone.shape != fixed_body.shape or support.shape != fixed_body.shape:
                raise ValueError(f"Mask grid mismatch at {index}")
            candidates = [{"forward_matrix_3x3": original["forward_matrix_3x3"]}] + original.get("candidates", [])
            scored = []
            for candidate in candidates:
                matrix = np.asarray(candidate["forward_matrix_3x3"], float).reshape(3, 3)
                aligned_body = remap_native(body, matrix, fixed_body.shape, nearest=True)
                aligned_bone = remap_native(bone, matrix, fixed_body.shape, nearest=True)
                bd = masked_dice(fixed_body, aligned_body)
                od = masked_dice(target_bone, aligned_bone, support)
                scored.append((1 - bd + 2 * (1 - od), matrix, aligned_body, aligned_bone, bd, od))
            _, matrix, aligned_body, aligned_bone, bd, od = min(scored, key=lambda value: value[0])
            fixed_bodies.append(fixed_body)
            moving_bodies.append(aligned_body)
            fixed_bones.append(target_bone)
            moving_bones.append(aligned_bone)
            supports.append(support)
            geometries.append(ct.metadata)
            transforms.append(matrix)
            records.append({"index": index, "global": original, "source_result": str(source_result),
                            "source_result_sha256": digest(source_result), "annotation": item,
                            "support_path": str(support_path), "body_before": bd, "bone_before": od,
                            "baseline_reranked_with_bone": not np.allclose(matrix.ravel(), original["forward_matrix_3x3"])})
            print(f"Prepared {index}: body={bd:.3f}, bone={od:.3f}", flush=True)
        audit["status"] = "optimizing"
        def progress(record):
            check_cancel()
            audit["trace"].append(record)
            (output / "audit.json").write_text(json.dumps(audit, indent=2), encoding="utf-8")
            print(f"Lattice {record['level']} iteration {record['iteration']}: loss={record['objective']:.5f}", flush=True)
        photo_indices = {str(Path(r["global"]["inputs"]["fixed"]["path"]).resolve()): i for i, r in enumerate(records)}
        regions = []
        for region in requested_regions:
            key = str(Path(region["photo_path"]).resolve())
            if key not in photo_indices:
                raise ValueError(f"Adaptive region photograph is absent or skipped: {key}")
            regions.append({**region, "sequence_index": photo_indices[key]})
        audit["adaptive_regions"] = regions
        if args.regions:
            audit["regions_sha256"] = digest(Path(args.regions))
        fit = fit_sequence(fixed_bodies, moving_bodies, fixed_bones, moving_bones, supports,
                           geometries, transforms, cfg, progress, check_cancel, regions)
        audit["roi"] = fit["roi"]
        audit["settings"] = fit["settings"]
        audit["continuity_links"] = [{"fixed_a": records[a]["index"], "fixed_b": records[b]["index"], "distance_mm": dz} for a, b, dz in fit["links"]]
        np.savez_compressed(output / "control_lattices.npz", nodes=fit["nodes"], roi=fit["roi"],
                            photo_to_patient_vectors=fit["physical_matrices"],
                            **{f"patch_{j}": p["nodes"] for j, p in enumerate(fit.get("patches", []))})
        for stage in fit["stages"]:
            np.savez_compressed(output / f"stage_{stage['level'] + 1:02d}_control_lattices.npz",
                                nodes=stage["nodes"], roi=fit["roi"],
                                **{f"patch_{j}": p["nodes"] for j, p in enumerate(stage.get("patches", []))})
        audit["stages"] = [{"level": stage["level"], "count": stage["count"],
                             "objective": stage["objective"], "adaptive": stage.get("adaptive", False)} for stage in fit["stages"]]
        local_fields = []
        for i, record in enumerate(records):
            check_cancel()
            roi = fit["roi"]
            field = dense_field(fit["nodes"][i], (roi[3], roi[2]), cfg.max_displacement_px)
            transform = transforms[i]
            original = record["global"]
            ct = read_ct(original["inputs"]["moving"]["path"])
            source_body = ct_body(ct)
            source_bone = ((ct.hu >= args.bone_threshold_hu) & ct.valid & (source_body != 0)).astype(np.uint8)
            selected = select_safe_field(field, transform, roi, source_body, source_bone,
                fixed_bodies[i], fixed_bones[i], supports[i], cfg, record["body_before"], record["bone_before"])
            base_scale, adaptive_scale = selected[-1], 0.
            if any(p["region"]["sequence_index"] == i for p in fit.get("patches", [])):
                delta = fitted_field(fit, i, (roi[3], roi[2])) - field
                selected = select_safe_field(delta, transform, roi, source_body, source_bone,
                    fixed_bodies[i], fixed_bones[i], supports[i], cfg, selected[1], selected[2], base=selected[0])
                adaptive_scale = selected[-1]
            field, bd, od, displacement, jmin, jmax, scale = selected
            scale = max(base_scale, adaptive_scale)
            local_fields.append(field)
            run = output / f"Head{record['index']:03d}"
            run.mkdir()
            stages = save_intermediate_stages(run, fit, i, fixed_bodies[i].shape, transform,
                source_body, source_bone, fixed_bodies[i], fixed_bones[i], supports[i], record, check_cancel)
            field_path = run / "local_field.npz"
            np.savez_compressed(field_path, displacement_xy=field.astype(np.float32), roi=np.array(roi),
                                output_shape=np.array(fixed_bodies[i].shape),
                                convention=np.array(FIELD_CONVENTION))
            bone_path = run / "moving_bone_hu.png"
            write_png(bone_path, source_bone * 255)
            fixed = read_image(original["inputs"]["fixed"]["path"])
            hu = remap_native(ct.hu, transform, fixed.shape, field, roi, border=-1024.)
            valid = remap_native(ct.valid.astype(np.uint8), transform, fixed.shape, field, roi, nearest=True)
            np.savez_compressed(run / "aligned_ct_hu.npz", hu=hu, valid=valid)
            aligned = window_hu(hu)
            write_png(run / "aligned.png", aligned)
            write_png(run / "blend.png", cv2.addWeighted(fixed, .5, aligned, .5, 0))
            body_before_original = original.get("body_dice")
            result = {**original, "algorithm": "global_plus_regional_mesh_v1", "status": "needs_review",
                      "candidates": [], "forward_matrix_3x3": transform.ravel().tolist(),
                      "inverse_matrix_3x3": np.linalg.inv(transform).ravel().tolist(),
                      "body_dice": bd, "baseline_source": record["source_result"],
                      "baseline_source_sha256": record["source_result_sha256"],
                      "global_body_dice_original": body_before_original,
                      "baseline_reranked_with_bone": record["baseline_reranked_with_bone"],
                      "local_deformation": {"status": "candidate" if scale else "rejected_no_safe_improvement",
                                            "field_path": str(field_path), "sha256": digest(field_path),
                                            "convention": "inverse residual in photo pixels, composed before native CT sampling",
                                            "roi": roi, "units": "photo_pixels", "step_scale": scale,
                                            "stages": stages,
                                            "base_step_scale": base_scale, "adaptive_step_scale": adaptive_scale,
                                            "adaptive_regions": [r for r in regions if r["sequence_index"] == i],
                                            "metrics": {"body_before": record["body_before"], "body_after": bd,
                                                        "bone_before": record["bone_before"], "bone_after": od,
                                                        "max_displacement_px": displacement, "minimum_jacobian": jmin,
                                                        "maximum_jacobian": jmax}, "settings": fit["settings"]},
                      "warnings": ["Regional candidate requires anatomical review; target-mask overlap is an optimization metric, not independent validation.",
                                   "CT bone reference is an experimental HU threshold; no labels outside the annotation support are assumed.",
                                   "Forward/inverse 3x3 matrices describe only the global component; use the residual field for the full mapping."]}
            result["inputs"] = dict(original["inputs"])
            for key, path in [("fixed_bone", Path(record["annotation"]["mask_path"])), ("moving_bone", bone_path),
                              ("fixed_annotation_support", Path(record["support_path"]))]:
                result["inputs"][key] = {"path": str(path), "sha256": digest(path)}
            result["inputs"].pop("reference_fixed_bone", None)
            (run / "result.json").write_text(json.dumps(result, indent=2, ensure_ascii=False), encoding="utf-8")
            audit["pairs"].append({"fixed_index": record["index"], "result": str(run / "result.json"), **result["local_deformation"]})
            print(f"Local {record['index']}: bone {record['bone_before']:.3f}->{od:.3f}, max {displacement:.1f}px, Jmin {jmin:.3f}, scale {scale}", flush=True)
        audit["post_gate_continuity_mm_per_mm"] = []
        for a, b, dz in fit["links"]:
            va = local_fields[a] @ fit["physical_matrices"][a].T
            vb = local_fields[b] @ fit["physical_matrices"][b].T
            rms = float(np.sqrt(np.mean(((va - vb) / dz) ** 2)))
            audit["post_gate_continuity_mm_per_mm"].append({"fixed_a": records[a]["index"], "fixed_b": records[b]["index"], "rms": rms})
        audit["status"] = "needs_review"
    except KeyboardInterrupt:
        audit["status"] = "cancelled"
        raise
    except Exception as exc:
        audit.update(status="failed", error=str(exc))
        raise
    finally:
        (output / "audit.json").write_text(json.dumps(audit, indent=2, ensure_ascii=False), encoding="utf-8")


if __name__ == "__main__":
    main()
